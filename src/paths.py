from pathlib import Path                  # أداة بايثون الحديثة للتعامل مع المسارات

# هذا الملف في src/paths.py، فجذر المشروع هو المجلد الأب لـ src
# parents[0] = src/  و  parents[1] = جذر المشروع
ROOT = Path(__file__).resolve().parents[1]

# ---------------------------------------------------------
# المجلدات
# ---------------------------------------------------------
RAW_DIR = ROOT / "data" / "raw"              # مدخلات خارجية لا تُعدَّل أبداً
PROCESSED_DIR = ROOT / "data" / "processed"  # ما يولّده المشروع من البيانات
MODELS_DIR = ROOT / "models"                 # النموذج المدرَّب وملحقاته
FIGURES_DIR = ROOT / "reports" / "figures"   # الرسومات PNG للرسالة
TABLES_DIR = ROOT / "reports" / "tables"     # الجداول CSV للرسالة

# ---------------------------------------------------------
# الملفات
# ---------------------------------------------------------
SOURCE_CSV = RAW_DIR / "Final_Phishing_Dataset_96k.csv"  # المصدر الأصلي
TRANCO_CSV = RAW_DIR / "top-1m.csv"                      # أشهر المواقع (تارانكو)
PHISHTANK_GZ = RAW_DIR / "phishtank.csv.gz"              # تصيد حديث مؤكد
OPENPHISH_TXT = RAW_DIR / "openphish.txt"                # تصيد حديث (مصدر ثانٍ)

DATASET_CSV = PROCESSED_DIR / "dataset_v2.csv"           # البيانات الجاهزة للتدريب
MODEL_FILE = MODELS_DIR / "model.joblib"                 # النموذج المحفوظ
FEATURES_JSON = MODELS_DIR / "feature_names.json"        # ترتيب الخصائص الثابت

INDEX_HTML = ROOT / "src" / "api" / "static" / "index.html"  # صفحة الواجهة


def ensure_dirs():
    """
    ينشئ المجلدات التي سيُكتب فيها إن لم تكن موجودة.

    يُستدعى في بداية أي سكربت يكتب ملفات، حتى يعمل المشروع مباشرة
    بعد استنساخه من git رغم أن مجلدات المخرجات ليست مرفوعة فيه.
    """
    for d in (PROCESSED_DIR, MODELS_DIR, FIGURES_DIR, TABLES_DIR):
        d.mkdir(parents=True, exist_ok=True)
