# 5. مصفوفة الارتباط بين الخصائص
# =========================================================
def plot_correlation(numeric, dead):
    """يرسم خريطة حرارية تبيّن قوة العلاقة بين كل خاصيتين."""
    live = numeric.drop(columns=dead)                         # نحذف الخصائص الميتة لأن ارتباطها غير معرّف
    corr = live.corr()                                        # حساب معامل ارتباط بيرسون بين كل عمودين

    plt.figure(figsize=(16, 13))                              # لوحة كبيرة لأن عدد الخصائص كبير
    sns.heatmap(corr, cmap="coolwarm", center=0, square=True,
                linewidths=0.3, cbar_kws={"shrink": 0.6})     # أزرق = علاقة عكسية، أحمر = علاقة طردية
    plt.title("Feature Correlation Matrix")                    # عنوان الرسمة
    plt.xticks(rotation=90, fontsize=7)                       # تدوير أسماء الأعمدة لتظهر كاملة
    plt.yticks(fontsize=7)                                    # تصغير خط أسماء الصفوف
    save_fig("02_correlation_matrix.png")                     # حفظ الرسمة

    pairs = []                                                # قائمة سنجمع فيها أزواج الخصائص شديدة الارتباط
    cols = corr.columns                                       # أسماء الخصائص
    for i in range(len(cols)):                                # المرور على الصفوف
        for j in range(i + 1, len(cols)):                     # المرور على الأعمدة بعدها فقط (تجنب التكرار)
            r = corr.iloc[i, j]                               # قيمة الارتباط بين الخاصيتين
            if abs(r) >= 0.90:                                # 0.90 حد عملي يدل على تكرار شبه تام للمعلومة
                pairs.append((cols[i], cols[j], round(r, 3)))  # نحفظ الزوج مع قيمة الارتباط

    print("\n🔗 أزواج خصائص ارتباطها ≥ 0.90 (معلومة مكررة):")
    if pairs:                                                 # إذا وُجدت أزواج
        for a, b, r in pairs:                                 # نطبعها كلها
            print(f"   - {a} ↔ {b} = {r}")
        print("   ➜ يمكن الاستغناء عن إحدى كل زوج لتبسيط النموذج.")
    else:
        print("   لا توجد خصائص مكررة بهذه القوة.")


