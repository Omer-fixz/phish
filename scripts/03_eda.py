# 8. طول الرابط حسب الفئة (قيد مذكور في حدود مجموعة البيانات)
# =========================================================
def plot_url_length_bias(df):
    """يوضّح أن الروابط الشرعية أقصر بكثير من التصيدية — وهو انحياز مصدر يجب ذكره."""
    m0 = df.loc[df["label"] == 0, "url_length"].mean()         # متوسط طول الرابط الشرعي
    m1 = df.loc[df["label"] == 1, "url_length"].mean()         # متوسط طول رابط التصيد
    print("\n📏 طول الرابط حسب الفئة:")
    print(f"   شرعي: {m0:.1f} حرفاً | تصيد: {m1:.1f} حرفاً")     # مقارنة مباشرة بين المتوسطين
    print("   ➜ فرق كبير كهذا يجعل url_length أقوى مما تستحق (انحياز مصدر يُذكر كقيد).")

    plt.figure(figsize=(7, 5))                                # لوحة رسم جديدة
    sns.boxplot(data=df, x="label", y="url_length", hue="label",
                palette=["#2e7d32", "#c62828"], legend=False, showfliers=False)  # صندوق لكل فئة بدون القيم الشاذة
    plt.title("URL Length by Class")                           # عنوان الرسمة
    plt.xlabel("label (0 = legitimate / 1 = phishing)")                  # تسمية توضح معنى الأرقام
    plt.ylabel("URL length (characters)")                            # تسمية المحور الرأسي
    save_fig("05_url_length_by_class.png")                     # حفظ الرسمة


