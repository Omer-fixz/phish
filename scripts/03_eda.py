# 3. توزيع الفئات (كم رابط تصيد وكم رابط شرعي)
# =========================================================
def plot_class_distribution(df):
    """يرسم أعمدة تبيّن عدد روابط كل فئة، ويطبع النسب المئوية."""
    counts = df["label"].value_counts().sort_index()          # عدّ الصفوف لكل قيمة تصنيف (0 ثم 1)
    total = len(df)                                           # إجمالي عدد الصفوف لحساب النسب

    print("\n📊 توزيع الفئات:")                                # عنوان في الشاشة
    for lbl, cnt in counts.items():                           # المرور على كل فئة مع عددها
        name = "تصيد" if lbl == 1 else "شرعي"                 # ترجمة الرقم إلى كلمة مفهومة
        print(f"   label={lbl} ({name}): {cnt} رابط = {cnt / total * 100:.2f}%")  # طباعة العدد والنسبة

    ratio = counts.max() / counts.min()                       # نسبة الفئة الأكبر إلى الأصغر (قياس الاتزان)
    print(f"   نسبة عدم التوازن = {ratio:.2f} : 1")            # كلما اقتربت من 1 كانت البيانات متوازنة

    plt.figure(figsize=(6, 4))                                # فتح لوحة رسم جديدة بحجم مناسب
    sns.barplot(x=counts.index.astype(str), y=counts.values, hue=counts.index.astype(str),
                palette=["#2e7d32", "#c62828"], legend=False)  # أعمدة: أخضر للشرعي وأحمر للتصيد
    plt.title("Class Distribution (0 = Legitimate / 1 = Phishing)")       # عنوان الرسمة
    plt.xlabel("label")                                       # تسمية المحور الأفقي
    plt.ylabel("Number of URLs")                              # تسمية المحور الرأسي
    for i, v in enumerate(counts.values):                     # المرور على كل عمود لكتابة رقمه فوقه
        plt.text(i, v, str(v), ha="center", va="bottom")      # كتابة العدد فوق العمود مباشرة
    save_fig("01_class_distribution.png")                     # حفظ الرسمة في مجلد figures


