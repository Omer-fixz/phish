# =========================================================
def load_data(path):
    """تقرأ ملف البيانات وتتأكد أنه موجود وأن أعمدته الأساسية سليمة."""
    if not path.exists():                                         # نتحقق أولاً أن الملف موجود فعلاً
        raise FileNotFoundError(f"لم يتم العثور على الملف: {path}")  # إذا لم يوجد نوقف البرنامج برسالة واضحة

    df = pd.read_csv(path, low_memory=False)                      # قراءة الملف كاملاً وتحويله إلى جدول
    print(f"✅ تم تحميل البيانات: {df.shape[0]} صف و {df.shape[1]} عمود")  # طباعة عدد الصفوف والأعمدة

    if "label" not in df.columns:                                 # عمود التصنيف إلزامي لأنه هدف التعلم
        raise ValueError("العمود 'label' غير موجود في الملف")      # نوقف البرنامج إذا كان مفقوداً
    if "url" not in df.columns:                                   # عمود الرابط إلزامي لأننا سنستخرج منه النطاق
        raise ValueError("العمود 'url' غير موجود في الملف")

    return df                                                     # نُرجع الجدول لبقية الدوال


# =========================================================
# 2. التأكد من وجود عمود النطاق (domain)
# عمود النطاق يبنيه سكربت 00_build_dataset.py، وهو مطلوب في المرحلة 2
# للتقسيم حسب النطاق. نتحقق هنا فقط، وإن غاب نبنيه بنفس الدالة الرسمية.
# =========================================================
def ensure_domain_column(df):
    """يتأكد أن عمود النطاق موجود، ويبنيه بالدالة الرسمية إن كان مفقوداً."""
    if "domain" not in df.columns:                          # إن كان الملف قديماً بلا عمود نطاق
        df["domain"] = df["url"].apply(get_domain)          # نبنيه بنفس دالة المستخرج الرسمي
    print(f"✅ عدد النطاقات الفريدة = {df['domain'].nunique()}")  # طباعة عدد النطاقات المختلفة
    return df


