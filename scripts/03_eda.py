# 6. توزيع أهم الخصائص حسب الفئة
# =========================================================
def plot_top_features(df, numeric, dead):
    """يقارن توزيع أهم الخصائص بين الروابط الشرعية والتصيدية."""
    live = numeric.drop(columns=dead)                         # نعمل على الخصائص الحية فقط

    # نحسب لكل خاصية الفرق بين متوسطها في فئة التصيد ومتوسطها في الفئة الشرعية،
    # مقسوماً على الانحراف المعياري — كلما كبر الفرق كانت الخاصية أقدر على التمييز.
    diffs = {}                                                # قاموس: اسم الخاصية ← قوة تمييزها
    for col in live.columns:                                  # المرور على كل خاصية
        m1 = live.loc[df["label"] == 1, col].mean()           # متوسط الخاصية في روابط التصيد
        m0 = live.loc[df["label"] == 0, col].mean()           # متوسط الخاصية في الروابط الشرعية
        sd = live[col].std()                                  # الانحراف المعياري لتوحيد وحدة القياس
        diffs[col] = abs(m1 - m0) / sd if sd > 0 else 0       # الفرق المعياري (نتفادى القسمة على صفر)

    top = sorted(diffs, key=diffs.get, reverse=True)[:6]      # ترتيب تنازلي وأخذ أقوى 6 خصائص
    print("\n⭐ أقوى الخصائص تمييزاً بين الفئتين:")
    for c in top:                                             # طباعة الخصائص الست مع قيمة الفرق
        print(f"   - {c}: فرق معياري = {diffs[c]:.3f}")

    fig, axes = plt.subplots(2, 3, figsize=(16, 9))           # شبكة رسومات 2×3 = ست رسومات في صورة واحدة
    for ax, col in zip(axes.flatten(), top):                  # ربط كل خانة في الشبكة بخاصية من الست
        data = df[[col, "label"]].copy()                      # نسخة صغيرة من البيانات لهذه الخاصية فقط
        upper = data[col].quantile(0.99)                      # حد أعلى عند الشريحة 99% لقص القيم الشاذة
        data = data[data[col] <= upper]                       # نستبعد 1% الأعلى حتى لا تُفسد شكل الرسمة
        sns.kdeplot(data=data, x=col, hue="label", fill=True, common_norm=False,
                    palette={0: "#2e7d32", 1: "#c62828"}, ax=ax)  # منحنى كثافة لكل فئة بلون مختلف
        ax.set_title(col)                                     # عنوان الرسمة الفرعية = اسم الخاصية
        ax.set_xlabel("")                                     # نخفي تسمية المحور لأن العنوان يكفي
    plt.suptitle("Top Discriminative Features by Class (green = legit / red = phishing)")  # عنوان عام للصورة
    save_fig("03_top_features_by_class.png")                  # حفظ الصورة


