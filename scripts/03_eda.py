# 7. فحص تكرار النطاقات (سبب إلزامية GroupShuffleSplit)
# =========================================================
def analyze_domains(df):
    """يقيس نسبة الروابط التي تنتمي لنطاقات مكررة — وهي مبرر التقسيم حسب النطاق."""
    counts = df["domain"].value_counts()                      # عدد الروابط لكل نطاق
    repeated = counts[counts > 1]                             # النطاقات التي ظهرت أكثر من مرة
    share = repeated.sum() / len(df) * 100                    # نسبة الروابط الواقعة داخل نطاقات مكررة

    print("\n🌐 تحليل النطاقات:")
    print(f"   عدد النطاقات الفريدة = {counts.shape[0]}")       # كم نطاقاً مختلفاً في البيانات
    print(f"   نطاقات متكررة = {repeated.shape[0]}")            # كم نطاقاً ظهر أكثر من مرة
    print(f"   نسبة الروابط داخل نطاقات مكررة = {share:.1f}%")   # الرقم الحاسم لتبرير التقسيم حسب النطاق
    print("   ➜ لهذا يجب استخدام GroupShuffleSplit في المرحلة 2 لمنع تسريب النطاق.")

    top10 = counts.head(10)                                   # أكثر عشرة نطاقات تكراراً
    plt.figure(figsize=(9, 5))                                # لوحة رسم أفقية
    sns.barplot(x=top10.values, y=top10.index, hue=top10.index,
                palette="viridis", legend=False)              # أعمدة أفقية لأن أسماء النطاقات طويلة
    plt.title("Top 10 Most Frequent Domains")             # عنوان الرسمة
    plt.xlabel("Number of URLs")                              # تسمية المحور الأفقي
    plt.ylabel("Domain")                                       # تسمية المحور الرأسي
    save_fig("04_top_domains.png")                            # حفظ الرسمة

    return share                                              # نُرجع النسبة لاستخدامها في الملخص


