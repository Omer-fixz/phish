# هذا هو مدخل التشغيل المحلي أثناء التطوير. أما النشر على خادم
# فيمر عبر Procfile الذي يشغّل uvicorn مباشرة.
# =========================================================

import os                            # لضبط متغير البيئة قبل تحميل التطبيق

# نُفعّل موقع التدريب في التشغيل المحلي فقط.
# يجب ضبط المتغير قبل استيراد التطبيق، لأن المسارات تُسجَّل وقت الاستيراد.
# ولا يُضبط إن كان المستخدم قد ضبطه بنفسه (مثلاً ENABLE_TRAINING=0 لإغلاقه).
os.environ.setdefault("ENABLE_TRAINING", "1")

import uvicorn                       # الخادم الذي يشغّل تطبيق FastAPI
from src.api.main import app         # التطبيق نفسه

if __name__ == "__main__":
    print("🔍 صفحة الفحص:   http://127.0.0.1:8000/")
    if os.environ.get("ENABLE_TRAINING", "").lower() in ("1", "true", "yes", "on"):
        print("⚙️  موقع التدريب: http://127.0.0.1:8000/training")

    # host محلي فقط في مرحلة التطوير: لا يقبل اتصالات من خارج الجهاز
    uvicorn.run(app, host="127.0.0.1", port=8000)
